package nvo.site;

import nvo.ProjectConfig;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * Синхронизира общия layout в ръчно писаните HTML страници.
 *
 * Страницата отбелязва местата с маркери; всичко между тях се презаписва:
 * <pre>
 *   &lt;!-- nv:head favicon="favicon-7.png" css="blog.css" --&gt; … &lt;!-- /nv:head --&gt;
 *   &lt;!-- nv:header active="7" --&gt; … &lt;!-- /nv:header --&gt;
 *   &lt;!-- nv:footer --&gt; … &lt;!-- /nv:footer --&gt;
 * </pre>
 * Параметри: active (4|7|10|12|home|balove|stats|blog), favicon, css (може няколко,
 * разделени със запетая), unsafe-eval="true". Пътят до корена се смята от дълбочината
 * на файла под docs/. Операцията е идемпотентна.
 *
 * Освен това генерира docs/js/ui/icons.js от {@link Icons}.
 *
 * Usage: java -cp nvo-v2.jar nvo.site.LayoutSync
 */
public final class LayoutSync {

    private static final Pattern BLOCK = Pattern.compile(
            "<!-- nv:(head|header|footer)((?:\\s+[a-z-]+=\"[^\"]*\")*)\\s*-->.*?<!-- /nv:\\1 -->",
            Pattern.DOTALL);
    private static final Pattern PARAM = Pattern.compile("([a-z-]+)=\"([^\"]*)\"");

    private LayoutSync() {
    }

    public static void main(String[] args) throws IOException {
        Path docs = Path.of(ProjectConfig.DOCS_DIR);
        List<Path> files = new ArrayList<>();
        try (Stream<Path> stream = Files.walk(docs)) {
            stream.filter(p -> p.toString().endsWith(".html"))
                    .filter(p -> !docs.relativize(p).startsWith("old"))
                    .forEach(files::add);
        }
        int changed = 0;
        for (Path file : files) {
            if (syncFile(docs, file)) {
                changed++;
            }
        }
        writeIconsModule(docs);
        System.out.println("LayoutSync: " + changed + " file(s) updated");
    }

    static boolean syncFile(Path docs, Path file) throws IOException {
        String html = Files.readString(file, StandardCharsets.UTF_8);
        if (!html.contains("<!-- nv:")) {
            return false;
        }
        int depth = docs.relativize(file).getNameCount() - 1;
        String root = SiteLayout.rootFor(depth);
        Matcher m = BLOCK.matcher(html);
        StringBuilder out = new StringBuilder();
        while (m.find()) {
            String kind = m.group(1);
            String params = m.group(2);
            SiteLayout.Page page = pageFor(root, params);
            String body = switch (kind) {
                case "head" -> SiteLayout.head(page);
                case "header" -> SiteLayout.header(page);
                default -> SiteLayout.footer(page);
            };
            String block = "<!-- nv:" + kind + params + " -->\n" + body + "  <!-- /nv:" + kind + " -->";
            m.appendReplacement(out, Matcher.quoteReplacement(block));
        }
        m.appendTail(out);
        String result = out.toString();
        if (result.equals(html)) {
            return false;
        }
        Files.writeString(file, result, StandardCharsets.UTF_8);
        return true;
    }

    private static SiteLayout.Page pageFor(String root, String params) {
        SiteLayout.Page page = new SiteLayout.Page(root);
        Matcher pm = PARAM.matcher(params == null ? "" : params);
        while (pm.find()) {
            String key = pm.group(1);
            String value = pm.group(2);
            switch (key) {
                case "active" -> page.active(value);
                case "favicon" -> page.favicon(value);
                case "css" -> {
                    for (String css : value.split(",")) {
                        page.css(css.trim());
                    }
                }
                case "unsafe-eval" -> page.unsafeEval("true".equals(value));
                default -> throw new IllegalArgumentException("Unknown layout parameter: " + key);
            }
        }
        return page;
    }

    private static void writeIconsModule(Path docs) throws IOException {
        StringBuilder js = new StringBuilder();
        js.append("// GENERATED by nvo.site.LayoutSync from Icons.java - DO NOT EDIT\n");
        js.append("const PATHS = {\n");
        for (Map.Entry<String, String> e : Icons.all().entrySet()) {
            js.append("  '").append(e.getKey()).append("': '")
                    .append(e.getValue().replace("\\", "\\\\").replace("'", "\\'"))
                    .append("',\n");
        }
        js.append("};\n\n");
        js.append("export function icon(name, cls) {\n");
        js.append("  const paths = PATHS[name];\n");
        js.append("  if (!paths) {\n");
        js.append("    throw new Error('Unknown icon: ' + name);\n");
        js.append("  }\n");
        js.append("  return '<svg class=\"icon' + (cls ? ' ' + cls : '') + '\" viewBox=\"0 0 24 24\" fill=\"none\" stroke=\"currentColor\" stroke-width=\"2\"'\n");
        js.append("    + ' stroke-linecap=\"round\" stroke-linejoin=\"round\" aria-hidden=\"true\" focusable=\"false\">' + paths + '</svg>';\n");
        js.append("}\n");
        Path target = docs.resolve("js/ui/icons.js");
        Files.createDirectories(target.getParent());
        String content = js.toString();
        if (!Files.exists(target) || !Files.readString(target, StandardCharsets.UTF_8).equals(content)) {
            Files.writeString(target, content, StandardCharsets.UTF_8);
        }
    }
}
