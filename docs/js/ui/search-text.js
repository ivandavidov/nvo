// Общ ключ за търсене: кирилица и латиница се сравняват еднакво („plovdiv“ → Пловдив,
// „sofia“/„sofiya“ → София), а съкращенията в имената на училищата се разписват
// („математическа гимназия“ → МГ, „средно училище“ → СУ).

// Латиница → кирилица, първо многобуквените съчетания (обтекаемата система + често срещани варианти).
const LATIN = [
  ['sht', 'щ'], ['zh', 'ж'], ['ts', 'ц'], ['ch', 'ч'], ['sh', 'ш'], ['yu', 'ю'], ['ya', 'я'],
  ['a', 'а'], ['b', 'б'], ['v', 'в'], ['w', 'в'], ['g', 'г'], ['d', 'д'], ['e', 'е'], ['z', 'з'],
  ['i', 'и'], ['y', 'й'], ['j', 'й'], ['k', 'к'], ['q', 'к'], ['l', 'л'], ['m', 'м'], ['n', 'н'],
  ['o', 'о'], ['p', 'п'], ['r', 'р'], ['s', 'с'], ['t', 'т'], ['u', 'у'], ['f', 'ф'], ['h', 'х'],
  ['c', 'ц'], ['x', 'кс']
];

/** Латинските букви в текста → кирилица (кирилицата остава същата). */
export function toCyrillic(str) {
  const s = String(str || '').toLowerCase();
  let out = '';
  for (let i = 0; i < s.length;) {
    const hit = /[a-z]/.test(s[i]) && LATIN.find(([lat]) => s.startsWith(lat, i));
    if (hit) {
      out += hit[1];
      i += hit[0].length;
    } else {
      out += s[i];
      i++;
    }
  }
  return out;
}

/**
 * Ключ за сравнение: малки букви, латиница → кирилица и изравнени двусмислени звукове
 * (я/иа, ю/иу, й/и, ь/и, ъ/а, щ/шт), за да съвпадат различните начини на изписване.
 * Прилага се и на заявката, и на текста, в който се търси.
 */
export function searchKey(str) {
  return toCyrillic(String(str || '').replace(/ё/gi, 'е'))
    .replace(/я/g, 'иа').replace(/ю/g, 'иу').replace(/[йь]/g, 'и').replace(/ъ/g, 'а').replace(/щ/g, 'шт')
    .replace(/и+/g, 'и')
    .replace(/\s+/g, ' ')
    .trim();
}

