/** Разписаните съкращения от име на училище (за добавяне към текста, в който се търси). */
export function expandAbbreviations(name) {
  const words = String(name || '').match(/[А-Яа-я]+/g) || [];
  const out = [];
  words.forEach((w) => {
    if (ABBREVIATIONS[w] && !out.includes(ABBREVIATIONS[w])) {
      out.push(ABBREVIATIONS[w]);
    }
  });
  return out.join(' ');
}
